import assert from 'node:assert/strict';
import { test } from 'node:test';

import { predictHolidays } from './predict_holidays.js';

// 기대값은 우주항공청 월력요항 원문(관보)에서 옮겨 적은 공휴일 날짜다 (일요일 자체는 제외).
// 2026년은 2026-04-30 「관공서의 공휴일에 관한 규정」 개정으로 추가된 노동절·제헌절을 포함한다.
//
// 2024·2025년은 전체 대조하지 않는다. 예측은 현행 법령만 적용하는데 두 해는 노동절·제헌절이
// 공휴일이 되기 전이고, 2025년에는 조기 대선(06-03)과 임시공휴일(01-27)까지 있어 맞출 수 없다.
// 현행 규칙으로도 성립하는 사례(2025-05-05 겹침 대체)만 따로 검증한다.
// https://www.kasa.go.kr/prog/plcyBrf/brief/kor/sub01_01_04/view.do?plcyBrfNo=431
const OFFICIAL_2026 = [
  '2026-01-01',
  '2026-02-16', '2026-02-17', '2026-02-18',
  '2026-03-01', '2026-03-02',
  '2026-05-01', '2026-05-05', '2026-05-24', '2026-05-25',
  '2026-06-03', '2026-06-06',
  '2026-07-17',
  '2026-08-15', '2026-08-17',
  '2026-09-24', '2026-09-25', '2026-09-26',
  '2026-10-03', '2026-10-05', '2026-10-09',
  '2026-12-25',
];

const OFFICIAL_2027 = [
  '2027-01-01',
  '2027-02-06', '2027-02-07', '2027-02-08', '2027-02-09',
  '2027-03-01',
  '2027-05-01', '2027-05-03', '2027-05-05', '2027-05-13',
  '2027-06-06',
  '2027-07-17', '2027-07-19',
  '2027-08-15', '2027-08-16',
  '2027-09-14', '2027-09-15', '2027-09-16',
  '2027-10-03', '2027-10-04', '2027-10-09', '2027-10-11',
  '2027-12-25', '2027-12-27',
];

function datesOf(year: number): string[] {
  const days = predictHolidays(year);
  assert.ok(days, `${year}년 예측이 없다`);
  return Object.keys(days).sort();
}

test('2026년 예측은 월력요항(개정 반영)과 일치한다', () => {
  assert.deepEqual(datesOf(2026), OFFICIAL_2026);
});

test('2027년 예측은 월력요항과 일치한다', () => {
  assert.deepEqual(datesOf(2027), OFFICIAL_2027);
});

test('평일에 공휴일이 겹치면 다음 비공휴일이 대체공휴일이다 (2025-05-05 어린이날·부처님오신날)', () => {
  const days = predictHolidays(2025);
  assert.ok(days);
  assert.deepEqual(days['2025-05-05'], ['어린이날', '부처님오신날']);
  assert.deepEqual(days['2025-05-06'], ['대체공휴일']);
});

test('임기만료 선거일을 공직선거법 제34조로 예측한다', () => {
  // 제22대 국회 임기만료 2028-05-29 → 50일 전 이후 첫 수요일
  assert.deepEqual(predictHolidays(2028)?.['2028-04-12'], ['국회의원선거']);
  // 대통령 임기만료 2030-06-03 → 70일 전 이후 첫 수요일
  assert.deepEqual(predictHolidays(2030)?.['2030-03-27'], ['대통령선거']);
  // 지방선거: 2030-06-05(수)는 다음 날이 현충일이라 다음 주 수요일로 미뤄진다 (제34조②)
  assert.deepEqual(predictHolidays(2030)?.['2030-06-12'], ['전국동시지방선거']);
});

test('음력 변환 범위(2050년)를 넘는 연도는 예측하지 않는다', () => {
  assert.equal(predictHolidays(2051), null);
});
